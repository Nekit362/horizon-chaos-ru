def main():
    with zipfile.ZipFile(SOURCE) as z:
        original = json.loads(z.read('assets/wyr/lang/en_us.json'))
        assert len(original) == len(RU), (len(original), len(RU))
        translated = dict(zip(original, RU))
        raw = json.dumps(translated, ensure_ascii=False, indent=2).encode('utf-8')
        out = ROOT / 'dist'
        out.mkdir(exist_ok=True)
        (ROOT / 'ru_ru.json').write_bytes(raw)
        with zipfile.ZipFile(out / 'wyr-1.0.0-ru-fabric-1.20.2.jar', 'w', zipfile.ZIP_DEFLATED) as target:
            for info in z.infolist():
                if info.filename != 'assets/wyr/lang/ru_ru.json':
                    target.writestr(info, z.read(info))
            target.writestr('assets/wyr/lang/ru_ru.json', raw)
        with zipfile.ZipFile(out / 'wyr-russian-resourcepack.zip', 'w', zipfile.ZIP_DEFLATED) as target:
            target.writestr('pack.mcmeta', json.dumps({'pack': {'pack_format': 18, 'description': 'Would You Rather — русский перевод (1.20.2)'}}, ensure_ascii=False))
            target.writestr('assets/wyr/lang/ru_ru.json', raw)
        (ROOT / 'source-sha256.txt').write_text(hashlib.sha256(SOURCE.read_bytes()).hexdigest()+'\n', encoding='utf8')
        print(f'Translated {len(translated)} keys; original jar unchanged.')

if __name__ == '__main__':
    main()
